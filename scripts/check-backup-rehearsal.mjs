import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import { browserBindings } from './browser-channel.mjs';
const bindings = browserBindings();
const {default:init,BrowserVault}=await import(new URL('nightfall_web.js',bindings));
import {checkBackupFile} from '../website/public/wallet-origin/backup-check.js';
await init({module_or_path:readFileSync(new URL('nightfall_web_bg.wasm',bindings))});
const fixture=JSON.parse(readFileSync(new URL('../target/webwallet-test-fixture.json',import.meta.url)));
const password='PUBLIC disposable test password';
const active=BrowserVault.fromLegacy(fixture.state,password);
const session={vault:active,generation:1};
const bytes=active.snapshot(), before=active.info();
const file={size:bytes.length, async arrayBuffer(){return bytes.slice().buffer;}};
let freed=0;
const restore=(bytes,password)=>{const candidate=BrowserVault.fromBackup(bytes,password);return {address:()=>candidate.address(),free(){freed++;candidate.free();}};};
const run=(overrides={})=>checkBackupFile({file,password,session,restore,...overrides});
assert.match(await run(),/Backup checked/);assert.equal(freed,1);assert.equal(active.info(),before);
await assert.rejects(run({password:'incorrect public password'}));
const other=BrowserVault.create(password,0);const otherBytes=other.snapshot();other.free();
await assert.rejects(run({file:{size:otherBytes.length,async arrayBuffer(){return otherBytes.buffer;}}}),/different wallet/);assert.equal(freed,2);
const broken=bytes.slice();broken[broken.length-1]^=1;
await assert.rejects(run({file:{size:broken.length,async arrayBuffer(){return broken.buffer;}}}));
await assert.rejects(run({file:{size:65*1024*1024,arrayBuffer(){throw new Error('must not read oversized file');}}}),/64 MiB/);
await assert.rejects(run({file:{size:bytes.length,async arrayBuffer(){session.generation++;return bytes.buffer;}}}),/session changed/);
assert.equal(active.info(),before);
active.free();
console.log('Backup Check: real WASM restore, mismatch, corruption, wrong password, size limit, session race; active wallet unchanged.');
